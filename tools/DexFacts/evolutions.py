#!/usr/bin/env python3
"""Builds the Poképark's evolution table: for each species, the one it evolves from and its
evolution family (so a Charmander can recognize a Charizard as what it may become).

Source: PokeAPI's CSV data (https://github.com/PokeAPI/pokeapi, data/v2/csv), BSD-3-Clause.

Usage:
    python3 tools/DexFacts/evolutions.py [pokemon_species.csv] [output]
        output defaults to src/PKForge.Domain/Resources/evolutions.tsv
"""
import csv
import io
import os
import sys
import urllib.request

URL = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species.csv"


def main():
    if len(sys.argv) > 1:
        text = open(sys.argv[1], encoding="utf-8").read()
    else:
        with urllib.request.urlopen(URL) as r:
            text = r.read().decode("utf-8")
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), "../../src/PKForge.Domain/Resources/evolutions.tsv")
    rows = [r for r in csv.DictReader(io.StringIO(text)) if int(r["id"]) <= 1025]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("# species\tevolves from (0: none)\tfamily. Generated by tools/DexFacts/evolutions.py from PokeAPI (BSD-3-Clause); do not edit.\n")
        for r in sorted(rows, key=lambda r: int(r["id"])):
            f.write(f"{r['id']}\t{r['evolves_from_species_id'] or 0}\t{r['evolution_chain_id']}\n")
    print(f"{len(rows)} species", file=sys.stderr)


if __name__ == "__main__":
    main()
