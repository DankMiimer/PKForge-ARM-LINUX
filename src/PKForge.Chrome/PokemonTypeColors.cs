using SkiaSharp;

namespace PKForge.Chrome;

/// <summary>The Android type plates' palette, shared with Linux.</summary>
public static class PokemonTypeColors
{
    private static readonly SKColor[] Palette =
    [
        new(0xA8,0xA7,0x7A), new(0xC2,0x2E,0x28), new(0xA9,0x8F,0xF3), new(0xA3,0x3E,0xA1), new(0xE2,0xBF,0x65), new(0xB6,0xA1,0x36),
        new(0xA6,0xB9,0x1A), new(0x73,0x57,0x97), new(0xB7,0xB7,0xCE), new(0xEE,0x81,0x30), new(0x63,0x90,0xF0), new(0x7A,0xC7,0x4C),
        new(0xF7,0xD0,0x2C), new(0xF9,0x55,0x87), new(0x96,0xD9,0xD6), new(0x6F,0x35,0xFC), new(0x70,0x57,0x46), new(0xD6,0x85,0xAD),
    ];
    public static SKColor ForType(int type) => type == PKForge.Domain.TypeFacts.Stellar ? new(0x3E, 0x8F, 0xB0)
        : (uint)type < Palette.Length ? Palette[type] : Pksm.ButtonBlue;
}

public static class MoveNumbers
{
    public static string Power(int power) => power > 0 ? power.ToString() : "—";
    public static string Accuracy(int accuracy) => accuracy > 0 ? accuracy.ToString() : "—";
}
